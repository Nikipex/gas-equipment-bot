from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CompareCard:
    title: str
    direct_answer: str
    comparison: list[tuple[str, str, str]]
    sales_logic: str
    must_check: list[str]


def find_compare_card(question: str) -> CompareCard | None:
    q = question.lower().replace("ё", "е")

    if "лемакс" in q and ("classic" in q or "классик" in q) and ("premium" in q or "премиум" in q):
        return CompareCard(
            title="Лемакс Classic vs Лемакс Premium",
            direct_answer=(
                "Classic — базовая бюджетная серия напольных котлов Лемакс. "
                "Premium — серия выше классом. Но точную техническую разницу нужно смотреть "
                "по конкретным моделям одной мощности."
            ),
            comparison=[
                ("Позиционирование", "Базовая бюджетная линейка", "Серия выше классом"),
                ("Клиентский сценарий", "Когда нужно дешевле и проще", "Когда клиент готов доплатить за вариант получше"),
                ("КПД", "Сверять по паспорту конкретной модели", "Сверять по паспорту конкретной модели"),
                ("Теплообменник", "Сверять толщину/конструкцию по паспорту", "Сверять толщину/конструкцию по паспорту"),
                ("Автоматика", "Сверять установленную автоматику", "Сверять установленную автоматику"),
                ("Вес", "Сверять вес конкретной мощности", "Сверять вес конкретной мощности"),
                ("Дымоход", "Сверять диаметр и расположение", "Сверять диаметр и расположение"),
            ],
            sales_logic=(
                "Classic предлагать, если клиент хочет минимальный бюджет и простую замену старого котла. "
                "Premium предлагать, если клиент готов доплатить за более старшую серию и хочет взять котёл «надолго»."
            ),
            must_check=[
                "одинаковую мощность, например 16 кВт против 16 кВт",
                "КПД по паспорту",
                "вес",
                "автоматику",
                "диаметр дымохода",
                "габариты и подключение",
            ],
        )

    if ("арту" in q or "artu" in q) and "сибер" in q:
        return CompareCard(
            title="Арту vs Сиберия",
            direct_answer=(
                "Арту можно рассматривать как бюджетную альтернативу Сиберии в сегменте простых "
                "напольных газовых котлов, но не как полную копию."
            ),
            comparison=[
                ("Позиционирование", "Бюджетная альтернатива", "Более узнаваемая серия на рынке"),
                ("Клиентский сценарий", "Когда важна низкая цена", "Когда клиенту важнее узнаваемость и привычный бренд"),
                ("Класс оборудования", "Простой напольный отопительный котёл", "Простой напольный отопительный котёл"),
                ("Мощность", "Подбирать строго ту же мощность", "Подбирать строго ту же мощность"),
                ("Автоматика", "Сверять конкретную модель", "Сверять конкретную модель"),
                ("Теплообменник", "Сверять по паспорту", "Сверять по паспорту"),
                ("Дымоход", "Сверять диаметр", "Сверять диаметр"),
            ],
            sales_logic=(
                "Если клиент давит на цену — можно показывать Арту. "
                "Если клиент сомневается и хочет более понятный бренд — проще аргументировать Сиберию."
            ),
            must_check=[
                "мощность",
                "энергонезависимость",
                "автоматику",
                "диаметр дымохода",
                "габариты",
                "подключение",
                "гарантию и сервис",
            ],
        )

    if "радиатор" in q and ("11" in q and "22" in q):
        return CompareCard(
            title="Радиатор тип 11 vs тип 22",
            direct_answer=(
                "Тип 11 тоньше и слабее по теплоотдаче. Тип 22 толще, мощнее и чаще используется, "
                "когда нужно больше тепла при той же высоте и длине."
            ),
            comparison=[
                ("Конструкция", "1 панель + 1 конвектор", "2 панели + 2 конвектора"),
                ("Толщина", "Тоньше", "Толще"),
                ("Теплоотдача", "Ниже", "Выше"),
                ("Вес", "Легче", "Тяжелее"),
                ("Цена", "Обычно дешевле", "Обычно дороже"),
                ("Когда предлагать", "Мало места по глубине / небольшая теплопотребность", "Нужно больше тепла без увеличения длины"),
            ],
            sales_logic=(
                "Тип 11 продавать, когда важна компактность и цена. "
                "Тип 22 продавать, когда клиенту нужна нормальная теплоотдача."
            ),
            must_check=[
                "высоту",
                "длину",
                "тип подключения",
                "межосевое/нижнее подключение",
                "теплоотдачу под помещение",
            ],
        )

    return None


def format_compare_card(card: CompareCard) -> str:
    lines: list[str] = []

    lines.append(f"Коротко:")
    lines.append(card.direct_answer)
    lines.append("")

    lines.append("Разница по делу:")
    for param, left, right in card.comparison:
        lines.append(f"- {param}: {left} / {right}")

    lines.append("")
    lines.append("Как продавать:")
    lines.append(card.sales_logic)

    lines.append("")
    lines.append("Что сверить перед КП:")
    for item in card.must_check:
        lines.append(f"- {item}")

    return "\n".join(lines)
