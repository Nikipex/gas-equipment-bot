from __future__ import annotations

import re


def get_thinking_context(question: str) -> str:
    q = question.lower().replace("ё", "е")
    blocks: list[str] = []

    if ("арту" in q or "артy" in q or "artu" in q) and ("сибер" in q):
        blocks.append("""
ТЕМА: Арту как бюджетный аналог Сиберии

Практическая логика для менеджера:
- Арту можно рассматривать как бюджетную альтернативу Сиберии в сегменте простых напольных газовых котлов.
- Сиберия обычно воспринимается клиентами как более известный и понятный бренд.
- Арту чаще продаётся через аргумент цены: "если нужен максимально недорогой напольник".
- Оба варианта чаще рассматриваются как замена старых АОГВ/КСГ, когда клиенту нужен простой отопительный котёл без сложной электроники.
- Нельзя говорить, что это 100% одинаковые котлы: нужно сверять конкретную модель.

Что сравнивать технически:
- мощность, например 11/16/20/25 кВт;
- энергонезависимость;
- автоматика;
- материал и конструкция теплообменника;
- КПД по паспорту;
- диаметр дымохода;
- габариты;
- расположение патрубков;
- гарантия и сервис.

Как отвечать:
- Если вопрос "реально ли аналог?" — отвечать прямо: "да, как бюджетную альтернативу рассматривать можно, но не как полную копию".
- Обязательно объяснять разницу: Сиберия — более узнаваемая/понятная клиенту, Арту — дешевле и проще продать по цене.
""".strip())

    if "лемакс" in q and ("classic" in q or "классик" in q) and ("premium" in q or "премиум" in q):
        blocks.append("""
ТЕМА: Лемакс Classic vs Лемакс Premium

Практическая логика:
- Classic — базовая бюджетная линейка напольных энергонезависимых котлов.
- Premium — линейка выше классом, которую обычно предлагают, когда клиент готов доплатить за более добротное исполнение.
- Classic продавать через цену и простоту.
- Premium продавать через "лучше взять надолго", более уверенное исполнение, более старшая серия.

Что сравнивать технически:
- КПД по паспорту конкретной мощности;
- мощностной ряд;
- толщину/конструкцию теплообменника, если указано в паспорте;
- вес конкретной модели: часто более добротная серия может быть тяжелее, но точные кг сверять по модели;
- автоматику;
- защитные функции;
- габариты;
- диаметр дымохода;
- подключение.

Как отвечать:
- Не писать "Premium лучше характеристиками" без расшифровки.
- Объяснить: Classic — когда нужен простой рабочий котёл дешевле; Premium — когда клиент хочет вариант классом выше.
- Если нет паспортных цифр, честно сказать: "точные КПД/вес сверяем по паспорту", но не уходить в воду.
""".strip())

    if re.search(r"\bbaxi\b|бакси|eco 4s|eco nova", q):
        blocks.append("""
ТЕМА: BAXI ECO 4S / ECO NOVA и аналоги

Для BAXI ECO 4S 24F важны признаки:
- настенный;
- двухконтурный;
- закрытая камера / турбо / FF;
- около 24 кВт.

Нельзя подменять:
- FF/турбо на CF/атмо;
- двухконтурный на одноконтурный;
- 24 кВт на сильно другую мощность без объяснения.

Практические аналоги искать среди:
- Navien Deluxe C/S 24;
- Ariston CARES/CLAS 24 FF;
- Federica Bugatti 24 Turbo;
- Ferroli 24 FF.
""".strip())

    if "радиатор" in q and ("11" in q or "22" in q):
        blocks.append("""
ТЕМА: Радиаторы тип 11 vs тип 22

Тип 11:
- одна панель;
- один конвектор;
- тоньше;
- легче;
- меньше теплоотдача;
- подходит, когда мало места по глубине или небольшая теплопотребность.

Тип 22:
- две панели;
- два конвектора;
- толще;
- тяжелее;
- выше теплоотдача при той же высоте и длине;
- чаще берут, когда нужно больше мощности без увеличения длины радиатора.

Как объяснять клиенту:
Тип 22 греет сильнее при тех же размерах по высоте/длине, но он толще и обычно дороже.
""".strip())

    return "\n\n---\n\n".join(blocks)
